def read_labels() -> list[str]:
    return json.loads(LABELS_FILE_PATH.read_text())


def get_system_prompt(prompt_file_name: str) -> str:
    """Helper to get read the system prompt from file."""
    prompt_full_path = PROMPT_DIR.joinpath(prompt_file_name)
    labels = "\n".join(read_labels())
    return prompt_full_path.read_text().format(label_names=labels)


def form_messages(system_prompt: str, user_query: str) -> list[dict]:
    """Helper to form the messages for chat input."""
    return [
        {
            "role": "system",
            "content": system_prompt,
        }
    ] + [
        {
            "role": "user",
            "content": user_query,
        }
    ]


def get_response_from_llm(
    user_query: str,
    prompt_file_name: str,
    model: PreTrainedModel,
    tokenizer: PreTrainedTokenizerBase,
) -> str:
    """Run the loop for getting the triage output.

    We intentionally pass both model and tokenizer, since we are using the
    models directly from mlx_lm.
    """

    system_prompt = get_system_prompt(prompt_file_name)
    messages = form_messages(system_prompt, user_query)

    prompt = tokenizer.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt",
    ).to(model.device)

    # for use later
    input_length = prompt["input_ids"].shape[1]

    labels_to_tokens_map = get_token_ids_for_labels(
        labels=read_labels(), tokenizer=tokenizer
    )

    token_processor = ConstrainedDecodingLogitsProcess(
        labels_to_tokens_map=labels_to_tokens_map,
        input_length=input_length,
        eos_token_id=tokenizer.eos_token_id,
    )

    stopping_criteria = AllowedSequencesBasedStoppingCriteria(
        labels_to_tokens_map=labels_to_tokens_map, input_length=input_length
    )

    outputs = model.generate(
        **prompt,
        max_length=input_length + 16,
        logits_processor=[token_processor],
        stopping_criteria=[stopping_criteria],
    )

    # once the stopping criteria/generation is complete, we can just
    # take the relevant allowed sequences and return the label
    allowed_sequences = get_allowed_sequences(
        generated_ids=outputs[0, input_length:],
        check_sequences=labels_to_tokens_map.values(),
    )

    label = [
        k
        for k in labels_to_tokens_map
        if labels_to_tokens_map[k] == allowed_sequences[0]
    ]

    return label[0]

